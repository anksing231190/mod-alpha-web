#!/usr/bin/env node
/* Generates apps/web/src/styles/theme-light.generated.css — the "Sand" (beige + cream) light theme.
   Every colour declaration in src/styles/base.css and src/styles/app.css is re-emitted under
   html[data-theme="light"] with its light counterpart (src/features/theme/theme-palette.js).
   Hand-designed refinements live in apps/web/src/styles/theme-light.css and load after this file.
   Run:  node scripts/build-light-theme.mjs   (also runs in `npm run build`) */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import postcss from 'postcss';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const web = path.join(root, 'apps/web');
const P = require(path.join(web, 'src/features/theme/theme-palette.js'));
const SOURCES = ['src/styles/base.css', 'src/styles/app.css'];
const SCOPE = 'html[data-theme="light"]';

const COLOR_TEST = /#[0-9a-fA-F]{3,8}\b|rgba?\(|\b(?:white|black)\b/;
const SKIP_VARS = new Set(['--c', '--fc', '--glow', '--fund-color', '--i', '--d', '--w', '--h']);
// Colourful icon tiles keep their original colours (as on the dark theme).
const ICON_SEL = /(^|[\s.#>+~-])(ic|icon|icons|ico|logo|brand-mark|mark|flag|emoji|fi|feat-ic|avatar-ic)([\s.:>+~\[-]|$)|-ic\b|-icon\b|icon-|ico-|\.v22-ic\b/;

function category(prop, value) {
  const p = prop.toLowerCase();
  if (p.startsWith('--')) {
    if (SKIP_VARS.has(p)) return null;
    if (/text|sub|muted|fg/.test(p)) return 'text';
    if (/border|line|stroke/.test(p)) return 'border';
    if (/shadow|glow/.test(p)) return 'shadow';
    if (/bg|panel|inner|surface|card|raised/.test(p)) return 'bg';
    return 'chart';
  }
  if (p === 'color' || p === 'caret-color' || p === '-webkit-text-fill-color' || p === 'text-decoration-color' || p === 'accent-color') return 'text';
  if (p.startsWith('background') || p === 'scrollbar-color') return 'bg';
  if (p.startsWith('border') || p.startsWith('outline') || p === 'column-rule-color') return 'border';
  if (p === 'box-shadow' || p === 'text-shadow' || p === 'filter' || p === '-webkit-filter') return 'shadow';
  if (p === 'fill' || p === 'stop-color' || p === 'flood-color') return 'fill';
  if (p === 'stroke') return 'stroke';
  return null;
}

function scopeSelector(sel) {
  return sel.split(',').map((s) => {
    s = s.trim();
    if (!s) return s;
    if (s.startsWith(':root')) return SCOPE + s.slice(5);
    if (s.startsWith('html')) return SCOPE + s.slice(4);
    return `${SCOPE} ${s}`;
  }).join(',\n');
}
const lightness = ([r, g, b]) => (Math.max(r, g, b) + Math.min(r, g, b)) / 510;
const baseSel = (s) => s.trim().replace(/::?[a-z-]+(\([^)]*\))?/g, '').trim();

let total = 0;
const outRoot = postcss.root();
outRoot.append(postcss.comment({ text: ' AUTO-GENERATED by scripts/build-light-theme.mjs — do not edit by hand. Refinements: src/styles/theme-light.css ' }));

for (const file of SOURCES) {
  const css = postcss.parse(fs.readFileSync(path.join(web, file), 'utf8'), { from: file });

  // 1) which selectors paint an accent (or gradient) background → white text on them stays white
  const accentBg = new Set();
  const strongSel = new Set();
  const strongBg = new Map();
  css.walkRules((rule) => {
    if (rule.parent?.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
    rule.walkDecls((d) => {
      if (!d.prop.startsWith('background')) return;
      const colors = d.value.match(P.COLOR_RE) || [];
      if (colors.some((c) => P.isAccent(c) && P.parse(c)[3] >= 0.6) || /var\(--v-(blue|violet|active|green|cyan)/.test(d.value)) rule.selectors.filter((s) => !/:(hover|focus|active|focus-visible|focus-within|:?after|:?before|:?placeholder|:?marker)/.test(s)).forEach((s) => accentBg.add(baseSel(s)));
      const strong = colors.filter((c) => P.isAccent(c));
      if (strong.length && strong.every((c) => { const x = P.parse(c); return x[3] >= 0.85 && P.mapColor(c, 'bg') !== c && lightness(x) < 0.8; })) rule.selectors.forEach((s) => strongSel.add(baseSel(s)));
    });
  });

  outRoot.append(postcss.comment({ text: ` ---- from ${file} ---- ` }));
  const emit = (node, target) => {
    node.each((child) => {
      if (child.type === 'atrule') {
        if (/keyframes|font-face|import|charset/.test(child.name)) return;
        const at = postcss.atRule({ name: child.name, params: child.params });
        emit(child, at);
        if (at.nodes && at.nodes.length) target.append(at);
        return;
      }
      if (child.type !== 'rule') return;
      const icon = ICON_SEL.test(child.selector);
      const clipText = child.some((d) => d.type === 'decl' && /background-clip$/.test(d.prop) && /text/.test(d.value));
      // white text stays white on an accent fill — painted by this element or by an ancestor in the selector
      const onAccent = (s) => { const b = baseSel(s); if (accentBg.has(b)) return true; const parts = b.split(/\s+|\s*>\s*/); for (let i = parts.length - 1; i > 0; i--) if (accentBg.has(parts.slice(0, i).join(' '))) return true; return false; };
      const keepWhite = child.selectors.some(onAccent);
      const decls = [];
      child.each((d) => {
        if (d.type !== 'decl') return;
        // colour-free values (transparent, none, var(--x), inherit …) are re-emitted unchanged so the cascade order is kept
        if (!COLOR_TEST.test(d.value)) { if (category(d.prop, d.value) && !d.prop.startsWith('--')) decls.push(postcss.decl({ prop: d.prop, value: d.value, important: d.important })); return; }
        if (/url\(/.test(d.value) && !/gradient/.test(d.value)) return;
        let cat = category(d.prop, d.value);
        if (!cat) return;
        if (cat === 'bg' && clipText) cat = 'gradtext';   // gradient headline words
        let value;
        if (cat === 'fill' || cat === 'stroke') {
          value = d.value.replace(P.COLOR_RE, (m) => {
            const c = P.parse(m); const neutral = c && !P.isAccent(m);
            if (icon) return neutral && cat === 'stroke' ? P.mapColor(m, 'border') : m;
            return neutral ? P.mapColor(m, cat === 'stroke' && c[3] < 0.7 ? 'border' : 'text') : P.mapColor(m, 'chart');
          });
        } else if (icon && (cat === 'bg' || cat === 'shadow' || cat === 'text')) {
          value = d.value.replace(P.COLOR_RE, (m) => (P.isAccent(m) || (cat === 'text' && /^(#fff|#ffffff|white)$/i.test(m)) ? (cat === 'shadow' ? P.mapColor(m, 'shadow') : m) : P.mapColor(m, cat)));
        } else if (cat === 'text' && keepWhite && child.selectors.some((s) => { const b = baseSel(s); if (strongSel.has(b)) return true; const parts = b.split(/\s+|\s*>\s*/); for (let i = parts.length - 1; i > 0; i--) if (strongSel.has(parts.slice(0, i).join(' '))) return true; return false; })) {
          // on a solid accent fill (now a deep caramel/plum/sage), text reads white
          value = d.value.replace(P.COLOR_RE, (m) => { const c = P.parse(m); return c && !P.isAccent(m) ? '#fff' : P.mapColor(m, 'text'); });
        } else {
          value = P.mapValue(d.value, cat, { keepWhite });
        }
        decls.push(postcss.decl({ prop: d.prop, value, important: d.important }));
      });
      if (!decls.length) return;
      // the `background` shorthand resets clip/size/position — re-emit the source longhands after it
      if (decls.some((d) => d.prop === 'background')) {
        child.each((d) => {
          if (d.type === 'decl' && /^(-webkit-)?background-(clip|size|position|repeat|origin|attachment|blend-mode)$/.test(d.prop)) decls.push(postcss.decl({ prop: d.prop, value: d.value, important: d.important }));
        });
      }
      const r = postcss.rule({ selector: scopeSelector(child.selector) });
      decls.forEach((d) => r.append(d));
      target.append(r);
      total += decls.length;
    });
  };
  emit(css, outRoot);
}

const outFile = path.join(web, 'src/styles/theme-light.generated.css');
fs.writeFileSync(outFile, outRoot.toResult().css + '\n');
console.log(`theme-light.generated.css: ${total} colour declarations mapped → ${path.relative(root, outFile)} (${(fs.statSync(outFile).size / 1024).toFixed(0)} KB)`);
