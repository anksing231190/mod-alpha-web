#!/usr/bin/env node
/**
 * Build apps/web/src/core/icons-lucide.js from the Lucide icon set (https://lucide.dev, ISC licence).
 *
 *   npm pack lucide-static && tar xzf lucide-static-*.tgz      # downloads package/icons/*.svg
 *   node scripts/data-tools/build-icons.mjs <path-to>/package/icons
 *
 * Only the icons the site uses are copied (the maps below). To add one: add `ourName: 'lucide-name'` to
 * OUTLINE (plain icons, ic()) or TILE (tinted tile icons, cic()), then run the script again.
 */
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir || !fs.existsSync(dir)) { console.error('usage: node scripts/data-tools/build-icons.mjs <lucide-static>/package/icons'); process.exit(1); }

// ic(name): our name → Lucide name
const OUTLINE = {
  search: 'search', x: 'x', chevDown: 'chevron-down', chevUp: 'chevron-up', chevL: 'chevron-left', chevR: 'chevron-right',
  arrowR: 'arrow-right', back: 'arrow-left', calendar: 'calendar', calCheck: 'calendar-check', clock: 'clock', star: 'star',
  user: 'user', users: 'users', lock: 'lock', eye: 'eye', info: 'info', target: 'target', bell: 'bell', trend: 'trending-up',
  bars: 'chart-column', bulb: 'lightbulb', crown: 'crown', percent: 'percent', rupee: 'indian-rupee', db: 'database',
  cloudUp: 'cloud-upload', check: 'check', checkCircle: 'circle-check', refresh: 'refresh-cw', grid: 'layout-grid',
  dash: 'layout-dashboard', card: 'credit-card', gear: 'settings', file: 'file-text', brain: 'brain', network: 'network',
  shield: 'shield-check', mail: 'mail', msg: 'message-square', bolt: 'zap', layers: 'layers', play: 'play', spark: 'sparkles',
  robot: 'bot', logout: 'log-out', sort: 'arrow-up-down', trophy: 'trophy', sliders: 'sliders-horizontal', mic: 'mic',
  wallet: 'wallet', help: 'circle-help', swap: 'arrow-left-right', download: 'download', plug: 'plug',
  menu: 'menu', compass: 'compass',
};
// cic(name): our name → [Lucide name, tint]
const TILE = {
  search: ['search', 'blue'], alarm: ['alarm-clock', 'amber'], chat: ['messages-square', 'violet'], sprout: ['palette', 'violet'],
  rocket: ['rocket', 'violet'], rocket2: ['rocket', 'violet'], crown: ['crown', 'amber'], check: ['circle-check', 'green'],
  cross: ['circle-x', 'rose'], shield: ['shield-check', 'green'], calendar: ['calendar-days', 'blue'], bank: ['landmark', 'blue'],
  idcard: ['id-card', 'blue'], db: ['database', 'cyan'], brain: ['brain', 'violet'], lock: ['lock', 'amber'], bell: ['bell', 'amber'],
  help: ['circle-help', 'blue'], chart: ['chart-line', 'green'], user: ['user', 'blue'], users: ['users', 'blue'],
  sliders: ['sliders-horizontal', 'blue'], mail: ['mail', 'blue'], sms: ['message-square-text', 'cyan'], phone: ['smartphone', 'cyan'],
  download: ['download', 'blue'], trash: ['trash-2', 'rose'], rupee: ['indian-rupee', 'green'], warn: ['triangle-alert', 'amber'],
  refund: ['receipt-indian-rupee', 'rose'], upload: ['upload', 'blue'], key: ['key-round', 'amber'], plug: ['plug', 'cyan'],
  clock: ['clock', 'blue'], globe: ['globe', 'cyan'], palette: ['palette', 'violet'], doc: ['file-text', 'blue'],
};

const inner = (name) => {
  const f = path.join(dir, name + '.svg');
  if (!fs.existsSync(f)) throw new Error('Lucide icon not found: ' + name);
  const s = fs.readFileSync(f, 'utf8');
  return s.slice(s.indexOf('>', s.indexOf('<svg')) + 1, s.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').replace(/\s+\/>/g, '/>').trim();
};
const paths = {};
for (const n of new Set([...Object.values(OUTLINE), ...Object.values(TILE).map((x) => x[0])])) paths[n] = inner(n);

const out = `/* ==========================================================================
   Core: icon set — generated by scripts/data-tools/build-icons.mjs, do not edit by hand.
   Icons: Lucide v${JSON.parse(fs.readFileSync(path.join(dir, '..', 'package.json'), 'utf8')).version} (https://lucide.dev) — ISC licence, see assets/icons/LUCIDE-LICENSE.txt
   MA_LUCIDE[lucideName] = inner SVG (24 × 24, stroke = currentColor)
   MA_ICON_OUTLINE[ourName] = lucideName   (ic())
   MA_ICON_TILE[ourName] = [lucideName, tint]   (cic())
   ========================================================================== */
const MA_LUCIDE = ${JSON.stringify(paths, null, 0).replace(/","/g, '",\n "')};
const MA_ICON_OUTLINE = ${JSON.stringify(OUTLINE)};
const MA_ICON_TILE = ${JSON.stringify(TILE)};
`;
const target = path.join(path.dirname(new URL(import.meta.url).pathname), '../../apps/web/src/core/icons-lucide.js');
fs.writeFileSync(target, out);
fs.mkdirSync(path.join(path.dirname(target), '../../assets/icons'), { recursive: true });
fs.copyFileSync(path.join(dir, '..', 'LICENSE'), path.join(path.dirname(target), '../../assets/icons/LUCIDE-LICENSE.txt'));
console.log(`wrote ${target} (${Object.keys(paths).length} icons)`);
