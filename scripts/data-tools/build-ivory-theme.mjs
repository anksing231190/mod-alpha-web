/**
 * Build apps/web/src/styles/theme-ivory.generated.css — the "Ivory" theme (white + cream).
 * Ivory is the Sand light theme with its cream/beige surfaces shifted towards white; text, accents, borders and
 * charts stay as in Sand. It reads the two Sand files, keeps only declarations whose colour actually changes,
 * and re-scopes each rule to html[data-theme="light"][data-skin="ivory"] (so it wins over Sand).
 *   node scripts/data-tools/build-ivory-theme.mjs
 * Re-run after editing theme-light.css or theme-light.generated.css.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dir = path.join(root, 'apps/web/src/styles');
const SRC = ['theme-light.generated.css', 'theme-light.css'];

const hex2rgb = (h) => { h = h.slice(1); if (h.length === 3) h = h.split('').map((c) => c + c).join(''); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)); };
const rgb2hex = (r) => '#' + r.map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('');
const lum = ([r, g, b]) => (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
/** Light, warm surface colours move ~70% towards a near-white (#fffefb); everything darker is left alone. */
function ivory(rgb) {
  const L = lum(rgb);
  if (L < 0.82) return null;
  const sat = Math.max(...rgb) - Math.min(...rgb);
  if (sat > 60) return null; // a real colour (e.g. a pale accent tint), not a cream surface
  const k = L > 0.93 ? 0.78 : 0.6, W = [255, 254, 251];
  return rgb.map((v, i) => v + (W[i] - v) * k);
}
function mapValue(v) {
  let changed = false;
  const out = v
    .replace(/#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b/g, (m) => { const n = ivory(hex2rgb(m)); if (!n) return m; changed = true; return rgb2hex(n); })
    .replace(/rgba?\((\d+),\s*(\d+),\s*(\d+)(\s*,\s*[\d.]+)?\)/g, (m, r, g, b, a) => { const n = ivory([+r, +g, +b]); if (!n) return m; changed = true; const [R, G, B] = n.map(Math.round); return a ? `rgba(${R},${G},${B}${a})` : `rgb(${R},${G},${B})`; });
  return changed ? out : null;
}
// :where() keeps each rule exactly as specific as in Sand, so Sand's own order (e.g. a selected button over a plain one) still holds
const scope = (sel) => sel.split(',').map((s) => s.trim()).filter(Boolean).map((s) => s.includes('html[data-theme="light"]') ? s.replace('html[data-theme="light"]', 'html[data-theme="light"]:where([data-skin="ivory"])') : `html[data-theme="light"]:where([data-skin="ivory"]) ${s}`).join(',');

let out = `/* GENERATED by scripts/data-tools/build-ivory-theme.mjs from the Sand light theme — do not edit by hand. */\n`;
let rules = 0;
for (const f of SRC) {
  const css = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  // walk top-level and @media blocks; rules are "selector { decls }"
  const walk = (text, depth) => {
    let i = 0, res = '';
    while (i < text.length) {
      const open = text.indexOf('{', i); if (open < 0) break;
      const head = text.slice(i, open).trim();
      // find matching brace
      let d = 1, j = open + 1; while (j < text.length && d) { if (text[j] === '{') d++; else if (text[j] === '}') d--; j++; }
      const body = text.slice(open + 1, j - 1);
      if (head.startsWith('@media') || head.startsWith('@supports')) { const inner = walk(body, depth + 1); if (inner) res += `${head}{${inner}}\n`; }
      else if (!head.startsWith('@') && head.includes('[data-theme="light"]')) {
        const decls = body.split(';').map((x) => x.trim()).filter(Boolean).map((dcl) => { const c = dcl.indexOf(':'); if (c < 0) return null; const p = dcl.slice(0, c).trim(), v = dcl.slice(c + 1).trim(); const nv = mapValue(v); return nv ? `${p}:${nv}` : null; }).filter(Boolean);
        if (decls.length) { res += `${scope(head)}{${decls.join(';')}}\n`; rules++; }
      }
      i = j;
    }
    return res;
  };
  out += walk(css, 0);
}
fs.writeFileSync(path.join(dir, 'theme-ivory.generated.css'), out);
console.log(`wrote theme-ivory.generated.css · ${rules} rules · ${(out.length / 1024).toFixed(0)} KB`);
