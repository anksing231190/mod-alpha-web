/**
 * Build apps/web/src/styles/theme-graphite.generated.css — the content colours of the "Graphite" theme
 * (charcoal + white). Graphite = Sand's layout with:
 *   • warm cream / beige surfaces, borders and text  → the same lightness in cool neutral grey (white pages)
 *   • caramel / ochre accents                        → slate blue-grey
 *   • plum accents (the second stop of Sand's button gradient) → deep slate
 * Data colours (green gains, red losses, chart blues/violets) are left as they are.
 * The charcoal sidebar / top bar come from theme-skins.css (data-skin="slate").
 * Every rule that sets a colour in a Sand-scoped rule is re-emitted under
 *   html[data-theme="light"]:where([data-skin="slate"]) …
 * :where() keeps each rule exactly as specific as in Sand, so Sand's own order still holds.
 *   node scripts/data-tools/build-graphite-theme.mjs     (re-run after editing the Sand styles)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dir = path.join(root, 'apps/web/src/styles');
const SRC = ['app.css', 'theme-light.generated.css', 'theme-light.css', 'robot.css', 'ai.css', 'ux.css'];

const hex2rgb = (h) => { h = h.slice(1); if (h.length === 3) h = h.split('').map((c) => c + c).join(''); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)); };
const rgb2hex = (r) => '#' + r.map((v) => Math.max(0, Math.min(255, Math.round(v))).toString(16).padStart(2, '0')).join('');
function rgb2hsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255; const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2; let h = 0, s = 0;
  if (mx !== mn) { const d = mx - mn; s = l > 0.5 ? d / (2 - mx - mn) : d / (mx + mn); h = mx === r ? (g - b) / d + (g < b ? 6 : 0) : mx === g ? (b - r) / d + 2 : (r - g) / d + 4; h *= 60; }
  return [h, s, l];
}
function hsl2rgb([h, s, l]) {
  const k = (n) => (n + h / 30) % 12, a = s * Math.min(l, 1 - l), f = (n) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return [f(0) * 255, f(8) * 255, f(4) * 255];
}
/** Map one Sand colour to Graphite; null = leave it. */
function graphite(rgb) {
  const [h, s, l] = rgb2hsl(rgb);
  const warm = h >= 15 && h <= 55, plum = h >= 300 && h <= 350;
  if (warm && (s < 0.45 || l > 0.82)) {           // cream / beige / brown neutrals → cool neutrals
    const L = l > 0.9 ? Math.min(1, l + (1 - l) * 0.75) : l;   // near-white surfaces become (almost) white
    return hsl2rgb([218, Math.min(s, 0.1) * 0.8, L]);
  }
  if (warm) return hsl2rgb([215, 0.28, Math.min(l, 0.42)]);      // caramel / ochre accent → slate
  if (plum && s > 0.15 && l < 0.6) return hsl2rgb([222, 0.3, Math.min(l, 0.36)]);
  return null;
}
function mapValue(v) {
  let changed = false;
  const out = v
    .replace(/#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b/g, (m) => { const n = graphite(hex2rgb(m)); if (!n) return m; changed = true; return rgb2hex(n); })
    .replace(/rgba?\((\d+),\s*(\d+),\s*(\d+)(\s*,\s*[\d.]+)?\)/g, (m, r, g, b, a) => { const n = graphite([+r, +g, +b]); if (!n) return m; changed = true; const [R, G, B] = n.map(Math.round); return a ? `rgba(${R},${G},${B}${a})` : `rgb(${R},${G},${B})`; });
  return changed ? out : null;
}
const SCOPE = 'html[data-theme="light"]:where([data-skin="slate"])';
const scope = (sel) => sel.split(',').map((s) => s.trim()).filter(Boolean).map((s) => s.includes('html[data-theme="light"]') ? s.replace('html[data-theme="light"]', SCOPE) : `${SCOPE} ${s}`).join(',');

let out = `/* GENERATED by scripts/data-tools/build-graphite-theme.mjs from the Sand light theme — do not edit by hand. */\n`;
let rules = 0;
for (const f of SRC) {
  const css = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  const walk = (text) => {
    let i = 0, res = '';
    while (i < text.length) {
      const open = text.indexOf('{', i); if (open < 0) break;
      const head = text.slice(i, open).trim();
      let d = 1, j = open + 1; while (j < text.length && d) { if (text[j] === '{') d++; else if (text[j] === '}') d--; j++; }
      const body = text.slice(open + 1, j - 1);
      if (head.startsWith('@media') || head.startsWith('@supports')) { const inner = walk(body); if (inner) res += `${head}{${inner}}\n`; }
      else if (!head.startsWith('@') && head.includes('[data-theme="light"]') && !head.includes('data-skin')) {
        // when any colour changes, the whole rule is re-emitted (unchanged lines too): a 'background' shorthand would
        // otherwise reset properties set next to it, e.g. background-clip:text on gradient headlines
        let changed = false;
        const decls = body.split(';').map((x) => x.trim()).filter(Boolean).map((dcl) => { const c = dcl.indexOf(':'); if (c < 0) return dcl; const p = dcl.slice(0, c).trim(), v = dcl.slice(c + 1).trim(); const nv = mapValue(v); if (nv) changed = true; return `${p}:${nv || v}`; });
        if (changed) { res += `${scope(head)}{${decls.join(';')}}\n`; rules++; }
      }
      i = j;
    }
    return res;
  };
  out += walk(css);
}
fs.writeFileSync(path.join(dir, 'theme-graphite.generated.css'), out);
console.log(`wrote theme-graphite.generated.css · ${rules} rules · ${(out.length / 1024).toFixed(0)} KB`);
